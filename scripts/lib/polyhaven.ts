/**
 * Poly Haven API client.
 *
 * Poly Haven is the backbone of this project's asset strategy: it is the only
 * CC0 library verified to carry photogrammetry-grade assets with PBR maps, and
 * it exposes a public JSON API so the pipeline is scriptable and reproducible
 * rather than a folder of hand-downloaded files.
 *
 * Everything here is read-only against the API. The API also documents a
 * "what to avoid" list for its CDN, so this module deliberately does NOT
 * prefetch or poll aggressively — a small fixed set of sequential requests.
 */

const API = "https://api.polyhaven.com";
const CDN = "https://dl.polyhaven.org/file/ph-assets";

export type GpuReport = { renderer: string | null; vendor: string | null };

export interface AssetInfo {
  name: string;
  polycount: number;
  max_resolution: number[];
  categories: string[];
  tags: string[];
  description: string;
  download_count: number;
  /** NOTE: this flag describes the .blend file, NOT the glTF export. The
   *  glTF ships a single mesh — LODs must be generated by us. See
   *  docs/ASSET_ASSESSMENT.md §1.2. */
  lods: boolean;
  geonodes: boolean;
}

export interface DownloadFile {
  url: string;
  md5: string;
  size: number;
  /** Sibling files a .gltf manifest needs: its .bin and all textures. */
  include?: Record<string, DownloadFile>;
}

export interface FileNode {
  url?: string;
  md5?: string;
  size?: number;
  include?: Record<string, DownloadFile>;
  /** The manifest file itself, for a resolution entry. */
  gltf?: DownloadFile;
}

export async function fetchInfo(id: string): Promise<AssetInfo> {
  const response = await fetch(`${API}/info/${id}`);
  if (!response.ok) throw new Error(`polyhaven info ${id}: HTTP ${response.status}`);
  return (await response.json()) as AssetInfo;
}

export async function fetchFiles(id: string): Promise<Record<string, FileNode>> {
  const response = await fetch(`${API}/files/${id}`);
  if (!response.ok) throw new Error(`polyhaven files ${id}: HTTP ${response.status}`);
  return (await response.json()) as Record<string, FileNode>;
}

/**
 * Geometry facts read from the actual glTF manifest.
 *
 * The API's `polycount` field is close to useless as a budget indicator: one
 * tree reports 312k polys while its manifest carries 3.68M vertices, because
 * the leaves are individual alpha cards. These numbers are what we budget on.
 */
export interface GlbStats {
  meshes: number;
  primitives: number;
  materials: string[];
  extensions: string[];
  /** Sum of unique POSITION accessor counts. */
  vertices: number;
  /** Sum of index accessor counts, divided by 3. */
  triangles: number;
  /** Total buffer bytes, uncompressed, as authored. */
  bytes: number;
  /** Per-primitive vertex counts, for deciding what to simplify. */
  perPrimitive: { material: string; vertices: number; triangles: number }[];
}

export async function readGlbStats(url: string): Promise<GlbStats> {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`manifest ${url}: HTTP ${response.status}`);

  const manifest = (await response.json()) as {
    meshes?: { primitives?: { attributes?: Record<string, number>; indices?: number; material?: number }[] }[];
    accessors?: { count: number }[];
    materials?: { name: string }[];
    extensionsUsed?: string[];
    buffers?: { byteLength: number }[];
  };

  const accessors = manifest.accessors ?? [];
  const materials = (manifest.materials ?? []).map((m) => m.name);
  const seenPositions = new Set<number>();
  const perPrimitive: GlbStats["perPrimitive"] = [];

  for (const mesh of manifest.meshes ?? []) {
    for (const primitive of mesh.primitives ?? []) {
      const positionAccessor = primitive.attributes?.POSITION;
      const vertices = positionAccessor != null ? (accessors[positionAccessor]?.count ?? 0) : 0;
      const indices = primitive.indices != null ? (accessors[primitive.indices]?.count ?? 0) : 0;

      if (positionAccessor != null) seenPositions.add(positionAccessor);
      perPrimitive.push({
        material: materials[primitive.material ?? 0] ?? "unnamed",
        vertices,
        triangles: Math.floor(indices / 3),
      });
    }
  }

  const vertices = [...seenPositions].reduce((sum, index) => sum + (accessors[index]?.count ?? 0), 0);
  const triangles = perPrimitive.reduce((sum, part) => sum + part.triangles, 0);
  const bytes = (manifest.buffers ?? []).reduce((sum, buffer) => sum + (buffer.byteLength ?? 0), 0);

  return {
    meshes: (manifest.meshes ?? []).length,
    primitives: perPrimitive.length,
    materials,
    extensions: manifest.extensionsUsed ?? [],
    vertices,
    triangles,
    bytes,
    perPrimitive,
  };
}

/** External buffer URIs referenced by a glTF manifest. */
async function readBufferUris(manifestUrl: string): Promise<string[]> {
  const response = await fetch(manifestUrl);
  if (!response.ok) return [];
  const manifest = (await response.json()) as { buffers?: { uri?: string }[] };
  return (manifest.buffers ?? [])
    .map((buffer) => buffer.uri)
    .filter((uri): uri is string => typeof uri === "string" && !uri.startsWith("data:"));
}

export interface ResolvedAsset {
  id: string;
  info: AssetInfo;
  /** The glTF manifest at the requested resolution. */
  manifestUrl: string;
  /** Every file needed: the .gltf, its .bin, and all textures. */
  files: { name: string; url: string; bytes: number }[];
  totalBytes: number;
  stats: GlbStats;
}

export interface ResolveOptions {
  /** "1k" | "2k" | "4k" | "8k". 1k is the default and the right choice for
   *  web: Poly Haven's 8K sets are for offline renderers and shipping them
   *  would exhaust shared VRAM on integrated graphics. */
  resolution?: "1k" | "2k" | "4k" | "8k";
}

/**
 * Resolve an asset to a concrete, downloadable file list plus real geometry
 * statistics measured from its manifest.
 */
export async function resolve(id: string, options: ResolveOptions = {}): Promise<ResolvedAsset> {
  const { resolution = "1k" } = options;

  const [info, files] = await Promise.all([fetchInfo(id), fetchFiles(id)]);
  const byResolution = (files.gltf as Record<string, FileNode> | undefined)?.[resolution];

  if (!byResolution?.gltf?.url) {
    const available = Object.keys(files.gltf ?? {}).join(", ") || "none";
    throw new Error(`${id}: no glTF at ${resolution} (available: ${available})`);
  }

  const manifest = byResolution.gltf;
  const include = manifest.include ?? {};
  const manifestName = manifest.url.split("/").pop() ?? `${id}.gltf`;

  // The .bin name is NOT derivable from the .gltf name — Poly Haven uses the
  // bare asset id ("pachira_aquatica_01.bin", not
  // "pachira_aquatica_01_1k.bin"). So it is read from the manifest's own
  // buffer URI rather than guessed, which is what a first pass got wrong.
  const bufferUris = await readBufferUris(manifest.url);
  const manifestDir = manifest.url.slice(0, manifest.url.lastIndexOf("/") + 1);

  const filesList = [
    { name: manifestName, url: manifest.url, bytes: manifest.size ?? 0 },
  ];

  for (const uri of bufferUris) {
    const head = await fetch(manifestDir + uri, { method: "HEAD" });
    filesList.push({
      name: uri.split("/").pop() ?? uri,
      url: manifestDir + uri,
      bytes: Number(head.headers.get("content-length") ?? 0),
    });
  }

  for (const [name, file] of Object.entries(include as Record<string, DownloadFile>)) {
    filesList.push({ name, url: file.url, bytes: file.size ?? 0 });
  }

  const stats = await readGlbStats(manifest.url);

  return {
    id,
    info,
    manifestUrl: manifest.url,
    files: filesList,
    totalBytes: filesList.reduce((sum, file) => sum + file.bytes, 0),
    stats,
  };
}

/** Direct URL for one texture of one asset, e.g. "jacaranda_tree", "diff", "1k". */
export function textureUrl(id: string, map: string, resolution: string): string | null {
  return `${CDN}/Models/jpg/${resolution}/${id}/${id}_${map}_${resolution}.jpg`;
}
